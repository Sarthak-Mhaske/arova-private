"""
RestoreIntent, LaunchPlan, and LaunchResult.

RestoreIntent describes *what the user wants to get back* — never how to launch it.
LaunchPlan is a reviewable collection of intents shown to the user before execution.
LaunchResult records what actually happened when an intent was executed.
"""
import time
from dataclasses import dataclass, field
from typing import Dict, Any, Optional, List

from .capabilities import Capability


@dataclass
class RestoreIntent:
    """
    A single thing the user wants restored.

    The planner produces these. The launcher consumes them.
    The planner never knows about executables, arguments, or OS commands.
    """
    kind: str
    """
    Semantic classification of the resource:
    'source_file', 'documentation', 'repository', 'terminal',
    'design_file', 'media', 'project', 'webpage', 'config_file'
    """

    capability: Capability
    """Which platform capability is needed to restore this resource."""

    resource_path: Optional[str] = None
    """Absolute path for local resources (files, folders, repos)."""

    resource_url: Optional[str] = None
    """URL for web resources."""

    preferred_application: Optional[str] = None
    """
    Hint, not requirement. The executable name or application display name
    learned from ApplicationAffinity.
    """

    app_id: Optional[str] = None
    """
    Canonical application identity (.desktop ID on Linux, CFBundleIdentifier on macOS,
    AppUserModelID / Registry identifier on Windows).
    """

    confidence: float = 0.0
    """How confident the planner is that this intent is correct (0.0–1.0)."""

    metadata: Dict[str, Any] = field(default_factory=dict)
    """Extra context: line, col, recent_command, cursor_position, etc."""

    priority: int = 5
    """1 = highest priority (restored first), 10 = lowest."""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "kind": self.kind,
            "capability": self.capability.name,
            "resource_path": self.resource_path,
            "resource_url": self.resource_url,
            "preferred_application": self.preferred_application,
            "app_id": self.app_id,
            "confidence": self.confidence,
            "metadata": self.metadata,
            "priority": self.priority,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "RestoreIntent":
        cap_name = data.get("capability", "OPEN_FILE")
        try:
            cap = Capability[cap_name]
        except KeyError:
            cap = Capability.OPEN_FILE
        return cls(
            kind=data.get("kind", "source_file"),
            capability=cap,
            resource_path=data.get("resource_path"),
            resource_url=data.get("resource_url"),
            preferred_application=data.get("preferred_application"),
            app_id=data.get("app_id"),
            confidence=data.get("confidence", 0.0),
            metadata=data.get("metadata", {}),
            priority=data.get("priority", 5),
        )


@dataclass
class LaunchPlan:
    """
    An ordered list of RestoreIntents generated by the RestorePlanner.

    Sent to the UI (Continue Card) for user review before execution.
    Execution only happens after ``approved`` is set to True.
    """
    workspace_id: str
    workspace_title: str
    intents: List[RestoreIntent] = field(default_factory=list)
    timestamp: float = field(default_factory=time.time)
    approved: bool = False

    def summary_for_ui(self) -> List[Dict[str, str]]:
        """Human-readable plan items for the Continue Card."""
        items = []
        for intent in sorted(self.intents, key=lambda i: i.priority):
            if intent.resource_path:
                import os
                resource_label = os.path.basename(intent.resource_path)
            elif intent.resource_url:
                resource_label = intent.resource_url[:60]
            else:
                resource_label = intent.kind

            app_label = intent.preferred_application or intent.app_id or "default"
            items.append({
                "action": intent.capability.name.replace("_", " ").title(),
                "resource": resource_label,
                "application": app_label,
                "kind": intent.kind,
                "confidence": f"{intent.confidence:.0%}",
            })
        return items

    def to_dict(self) -> Dict[str, Any]:
        return {
            "workspace_id": self.workspace_id,
            "workspace_title": self.workspace_title,
            "intents": [i.to_dict() for i in self.intents],
            "timestamp": self.timestamp,
            "approved": self.approved,
            "summary": self.summary_for_ui(),
        }


@dataclass
class LaunchResult:
    """
    The outcome of executing a single RestoreIntent.

    Produced by the PlatformBackend/Launcher and enriched by IntentExecutor.
    Tracks exact launch status, window focus state, and actual usage for
    the ApplicationAffinity feedback loop.
    """
    intent: RestoreIntent
    success: bool
    application_name: str
    detail: str
    pid: Optional[int] = None
    error: Optional[str] = None
    executed: bool = True
    focused: bool = False
    actually_used: bool = False
    dismissed: bool = False
    app_id: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "intent": self.intent.to_dict(),
            "success": self.success,
            "application_name": self.application_name,
            "detail": self.detail,
            "pid": self.pid,
            "error": self.error,
            "executed": self.executed,
            "focused": self.focused,
            "actually_used": self.actually_used,
            "dismissed": self.dismissed,
            "app_id": self.app_id,
        }
