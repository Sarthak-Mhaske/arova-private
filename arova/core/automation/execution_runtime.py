import logging
import asyncio
import threading
import time
import datetime
from typing import Optional, Any, List, Dict
from arova.core.events import RuntimeEventBus
from arova.core.automation.schema import ExecutionGraph, CapabilityRequest, NodeState
from arova.core.automation.dispatcher import ActionDispatcher

logger = logging.getLogger(__name__)

class ExecutionRuntime:
    """
    Dedicated state machine for executing ExecutionGraphs safely.
    Operates independently of IntentRuntime to prevent looping user intents.
    
    CRITICAL: The EventBus dispatches listeners from a ThreadPoolExecutor,
    NOT from an asyncio event loop. We must bridge from the thread callback
    into an asyncio loop to run async dispatcher methods.
    """
    def __init__(self, event_bus: RuntimeEventBus, dispatcher: ActionDispatcher):
        self._event_bus = event_bus
        self._dispatcher = dispatcher
        self._active_graph: Optional[ExecutionGraph] = None
        self._active_turn_id: Optional[str] = None
        self._active_feedback: Optional[str] = None
        self._plan_history: List[Dict[str, Any]] = []
        self._simulation_mode = False
        self._cancel_requested = False
        self._lock = threading.Lock()
        
        self._event_bus.subscribe("automation", "GRAPH_EXECUTION_REQUESTED", self._on_graph_execution_requested)
        self._event_bus.subscribe("runtime", "INTERRUPT_REQUESTED", self._on_interrupt)
        logger.info("ExecutionRuntime: Started and listening for automation events.")

    def _on_interrupt(self, payload: Any):
        logger.info("ExecutionRuntime: Interrupt requested. Setting cancel flag.")
        self._cancel_requested = True

    def set_simulation_mode(self, enabled: bool):
        self._simulation_mode = enabled
        logger.info(f"ExecutionRuntime: Simulation Mode = {enabled}")

    def _on_graph_execution_requested(self, payload: Any):
        """Called from EventBus ThreadPoolExecutor thread — NOT an async context."""
        if hasattr(payload, 'data') and isinstance(payload.data, dict):
            graph = payload.data.get("graph")
        else:
            graph = getattr(payload, "graph", None)
        
        if not graph:
            logger.error("ExecutionRuntime received empty graph request.")
            return
            
        if hasattr(payload, 'data') and isinstance(payload.data, dict):
            turn_id = payload.data.get("turn_id")
            feedback_message = payload.data.get("feedback_message")
        else:
            turn_id = getattr(payload, "turn_id", None)
            feedback_message = getattr(payload, "feedback_message", None)
            
        with self._lock:
            if self._active_graph:
                logger.info("ExecutionRuntime: Preempting active graph for new execution request.")
                self._cancel_requested = True
                # Allow reset for new graph
                self._active_graph = None
            
            self._cancel_requested = False
            
            # Convert ExecutionNode to CapabilityRequest if necessary
            if hasattr(graph, 'nodes') and graph.nodes and type(graph.nodes[0]).__name__ == 'ExecutionNode':
                from arova.core.automation.schema import CapabilityRequest, RiskLevel, NodeState
                capability_nodes = []
                for n in graph.nodes:
                    req = CapabilityRequest(
                        id=n.id,
                        action=n.capability_name,
                        capability=n.capability_name,
                        payload=n.args,
                        expected_observation="Action completed",
                        success_criteria="Return code 0",
                        confidence=1.0,
                        confidence_reason="Generated by trusted cognition router",
                        risk_level=RiskLevel.SYSTEM,
                        state=NodeState.QUEUED
                    )
                    capability_nodes.append(req)
                graph.nodes = capability_nodes
                
            self._active_graph = graph
            self._active_turn_id = turn_id
            self._active_feedback = feedback_message

            # Create initial plan record for UI projection
            graph_name = getattr(graph, "goal", getattr(graph, "name", "Execution Architecture"))
            plan_record = {
                "plan_id": graph.id,
                "title": graph_name,
                "when": datetime.datetime.now().strftime("%I:%M %p"),
                "timestamp": time.time(),
                "status": "Running",
                "progress": 0,
                "nodes": []
            }
            for n in graph.nodes:
                state_val = n.state.value if hasattr(n.state, "value") else str(n.state)
                plan_record["nodes"].append({
                    "id": getattr(n, "id", str(n)),
                    "capability": getattr(n, "capability", getattr(n, "action", str(n))),
                    "action": getattr(n, "action", getattr(n, "capability", str(n))),
                    "payload": getattr(n, "payload", getattr(n, "args", {})),
                    "state": state_val,
                    "output": None,
                    "error": None
                })
            self._plan_history.insert(0, plan_record)
            if len(self._plan_history) > 50:
                self._plan_history = self._plan_history[:50]
        
        # Schedule onto asyncio loop. The EventBus calls us from a thread,
        # so we try multiple strategies to get the coroutine running.
        logger.info("ExecutionRuntime: Scheduling execution loop...")
        
        # Strategy 1: Try to schedule onto a running asyncio loop
        try:
            loop = asyncio.get_event_loop()
            if loop.is_running():
                future = asyncio.run_coroutine_threadsafe(self._execution_loop(), loop)
                logger.info(f"ExecutionRuntime: Scheduled via run_coroutine_threadsafe")
                return
        except RuntimeError:
            pass
        
        # Strategy 2: Run in a new thread with its own event loop
        logger.info("ExecutionRuntime: No running loop found, spawning dedicated thread.")
        thread = threading.Thread(target=self._run_loop_in_thread, daemon=True)
        thread.start()
    
    def _run_loop_in_thread(self):
        """Fallback: create a new event loop in a thread and run the execution loop."""
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        try:
            loop.run_until_complete(self._execution_loop())
        finally:
            loop.close()

    async def _execution_loop(self):
        graph_name = getattr(self._active_graph, "goal", getattr(self._active_graph, "name", "Unknown Graph"))
        logger.info(f"ExecutionRuntime: Starting loop for graph: {graph_name}")
        
        if self._simulation_mode:
            logger.info("ExecutionRuntime: RUNNING IN SIMULATION MODE (Dry-Run)")
            
        results = []
        success = True
        try:
            # Check pre-flight confidence for all nodes first
            for node in self._active_graph.nodes:
                if node.state == NodeState.QUEUED and node.confidence < 0.45:
                    logger.warning(f"ExecutionRuntime: Halting. Node '{node.action}' has low confidence ({node.confidence}). Reason: {node.confidence_reason}")
                    node.state = NodeState.WAITING
                    self._emit_state(node)
                    success = False
                    break
            
            if not success:
                self._cleanup_after_execution(success=False, results=results)
                return

            import re
            context_variables = {}
            
            def _resolve_payload(payload, context):
                if isinstance(payload, str):
                    def repl(match):
                        key = match.group(1)
                        return str(context.get(key, match.group(0)))
                    return re.sub(r'\{\{(.*?)\.output\}\}', repl, payload)
                elif isinstance(payload, dict):
                    return {k: _resolve_payload(v, context) for k, v in payload.items()}
                elif isinstance(payload, list):
                    return [_resolve_payload(i, context) for i in payload]
                return payload

            # Dispatch nodes sequentially so the UI can show dynamic status for each one
            for node in self._active_graph.nodes:
                if self._cancel_requested:
                    logger.info("ExecutionRuntime: Preemption requested. Halting graph execution loop.")
                    self._cleanup_after_execution(success=False, results=results)
                    return

                if node.state != NodeState.QUEUED:
                    continue
                    
                node.state = NodeState.RUNNING
                self._update_plan_node(node.id, node.state.value)
                self._emit_state(node)
                
                # Apply data piping
                if node.payload:
                    node.payload = _resolve_payload(node.payload, context_variables)
                
                logger.info(f"ExecutionRuntime: Dispatching node '{node.action}' -> capability '{node.capability}' with payload: {node.payload}")
                
                try:
                    obs = await self._dispatcher.dispatch(node, simulation_mode=self._simulation_mode)
                    if obs.success:
                        node.state = NodeState.COMPLETED
                        context_variables[node.id] = obs.output
                        results.append({"action": node.action, "status": "success", "output": obs.output})
                        self._update_plan_node(node.id, node.state.value, output=obs.output)
                        logger.info(f"ExecutionRuntime: Node '{node.action}' completed. Output: {obs.output}")
                    else:
                        node.state = NodeState.FAILED
                        results.append({"action": node.action, "status": "failed", "error": obs.error})
                        self._update_plan_node(node.id, node.state.value, error=obs.error)
                        logger.error(f"ExecutionRuntime: Node '{node.action}' failed: {obs.error}")
                        success = False
                except Exception as exc:
                    node.state = NodeState.FAILED
                    results.append({"action": node.action, "status": "failed", "error": str(exc)})
                    self._update_plan_node(node.id, node.state.value, error=str(exc))
                    logger.error(f"ExecutionRuntime: Node '{node.action}' failed with exception: {exc}")
                    success = False
                
                self._emit_state(node)
        except Exception as e:
            logger.error(f"ExecutionRuntime: Exception during execution loop: {e}", exc_info=True)
            success = False
        finally:
            turn_id = getattr(self, "_active_turn_id", None)
            feedback = getattr(self, "_active_feedback", None)
            
            with self._lock:
                if self._active_graph:
                    for plan in self._plan_history:
                        if plan["plan_id"] == self._active_graph.id:
                            plan["status"] = "Completed" if success else "Failed"
                            if success:
                                plan["progress"] = 100
                            break
            
            # Emit completion event so IntentRuntime can report back to user
            self._event_bus.emit("automation", "GRAPH_EXECUTION_COMPLETED", {
                "graph_id": self._active_graph.id,
                "turn_id": turn_id,
                "feedback_message": feedback,
                "success": success,
                "results": results
            })
            
            with self._lock:
                self._active_graph = None
                self._active_turn_id = None
                self._active_feedback = None
            logger.info("ExecutionRuntime: Graph execution finished.")

    def _update_plan_node(self, node_id: str, state: str, output: Optional[Any] = None, error: Optional[str] = None):
        with self._lock:
            if not self._plan_history or not self._active_graph:
                return
            active_id = self._active_graph.id
            for plan in self._plan_history:
                if plan["plan_id"] == active_id:
                    total_nodes = len(plan["nodes"])
                    completed_nodes = 0
                    for n in plan["nodes"]:
                        if n["id"] == node_id:
                            n["state"] = state
                            if output is not None:
                                n["output"] = str(output)
                            if error is not None:
                                n["error"] = str(error)
                        if str(n.get("state")).upper() in ("COMPLETED", "FAILED", "SKIPPED"):
                            completed_nodes += 1
                    if total_nodes > 0:
                        plan["progress"] = int((completed_nodes / total_nodes) * 100)
                    break

    def get_all_plans(self) -> List[Dict[str, Any]]:
        with self._lock:
            return list(self._plan_history)

    def _emit_state(self, node: CapabilityRequest):
        turn_id = getattr(self, "_active_turn_id", None)
        self._event_bus.emit("automation", "NODE_STATE_CHANGED", {
            "id": node.id,
            "action": node.action,
            "state": node.state.value,
            "turn_id": turn_id
        })
